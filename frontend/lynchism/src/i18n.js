const LanguageContext = createContext();

export const LanguageProvider = ({ children }) => {
  const [hasChosenLang, setHasChosenLang] = useState(() => {
    return Boolean(localStorage.getItem("preferred_lang"));
  });

  const [lang, setLang] = useState(() => {
    return localStorage.getItem("preferred_lang") || "ua";
  });

  const setLanguage = (newLang) => {
    setLang(newLang);
    setHasChosenLang(true);
    localStorage.setItem("preferred_lang", newLang);
  };

  const closeLangModal = () => {
    setHasChosenLang(true);
    localStorage.setItem("preferred_lang", lang || "ua");
  };

  const t = (key) => {
    return translations[lang]?.[key] || translations["ua"]?.[key] || translations["en"]?.[key] || key;
  };

  const loc = (ua, en, ru) => {
    if (lang === 'en') return en;
    if (lang === 'ua') return ua;
    return ru || en || ua;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLanguage, hasChosenLang, closeLangModal, t, loc }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useTranslation = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useTranslation must be used within a LanguageProvider");
  }
  return context;
};
